package tiposDeVariaveis;

public class tiposNumericos {
	
	public static void main(String[] args) {
		Byte numeroBytee = 13;  // Essa variavel armazena de -128 até 127 ,nada acima disso
		
		Short numeroShort = 1;  // -32768 até 32767
		
		Integer  numeroInteger = 1; // -2147483648 até 2147483647 (2^31 "dois elevado a trigessima ptencia", até 2^31 -1)
		
		Long numeroLong = 1L; // - 9,223,372,036,854,775,808 até  9,223,372,036,854,775,807  ( 2^63 "dois levado a sexagéssima potencia", até 2^63 -1)
		
		
		
		Float numeroFloat = 1.0f; // como no long aqui precisa declarar letra f no float e no long a letra L
		
		Double numeroDouble = 1.0;
	}
	
	
}
